function fromPairs(subject,id,name,pairs,ask,explain,wrongPool=null){
 if(pairs.length!==15)throw Error(name+" pairs: "+pairs.length);
 const all=wrongPool||pairs.map(x=>x[1]);
 add(subject,id,name,pairs.map(([prompt,answer],i)=>({
  question:ask(prompt,answer,i),answer:String(answer),
  distractors:[all[(i+4)%all.length],all[(i+7)%all.length],all[(i+10)%all.length]].map(String),
  explanation:explain(prompt,answer,i)
 })));
}
function facts(subject,id,name,rows){
 if(rows.length!==15)throw Error("Invalid fact count "+name);
 add(subject,id,name,rows.map(([question,answer,distractors,explanation])=>({
  question,answer:String(answer),distractors:distractors.map(String),explanation:explanation||("सही उत्तर "+answer+" है।")
 })));
}
function calc(question,result,explanation,spread=1){
 if(!Number.isSafeInteger(result)||result<0)throw Error("Invalid numeric answer "+question+": "+result);
 const wrong=unique([result+spread,result+2*spread,Math.max(0,result-spread),Math.max(0,result-2*spread),result+3*spread,result+4*spread])
  .filter(a=>a!==result).slice(0,3);
 if(wrong.length!==3)throw Error("No distractors "+question);
 return {question,answer:String(result),distractors:wrong,explanation};
}
